draft = """Six jours avant la sixième épreuve, dans le bureau du chef du Clan du Poison, situé dans le manoir dudit clan, à l'ouest du château du Culte Démoniaque.

De nombreux dirigeants du Clan du Poison y étaient rassemblés, mais tous affichaient une mine sombre. Cela faisait suite à la requête reçue ce matin-là de la part de l'Académie Démoniaque concernant la sixième épreuve. Personne ne s'attendait à ce que la situation prenne une telle tournure.

Lorsque les cinq autres clans avaient appris que Chun Yeowun comptait défier le Premier Ancien Mu Jinwon, ils s'en étaient réjouis. Le Clan de la Sagesse avait vu sa puissance croître considérablement au cours de ces trois dernières années, tandis que les Clans du Poison et de l'Épée s'étaient grandement affaiblis.

'Nous espérons que le Clan de la Sagesse subira les pressions découlant de ce duel.'

Pour l'heure, Chun Yeowun agissait comme un poison exquis. Pour Mu Jinwon, il était impératif de tuer Yeowun lors de ce duel afin que son petit-fils devienne l'unique candidat légitime au trône. Cependant, au vu des événements récents, ce duel offrirait assurément au Seigneur une occasion de réprimer le Clan de la Sagesse, ce qui s'avérait être une situation gagnant-gagnant pour les autres clans.

« Ancien, vous devez refuser cette requête. Vous avez été libéré de prison il y a quelques mois à peine. L'œil du Seigneur est toujours braqué sur nous. »

C'était le conseiller du Clan du Poison qui s'adressait à Baek Oh. La situation était bien différente de l'époque où certains insistaient pour envoyer un assassin tuer Yeowun. Tout avait changé.

« Mon opinion reste inchangée. Si nous subissons davantage d'oppression, cela pourrait détruire l'équilibre des pouvoirs entre les six clans. »

Baek Chau, l'ancien chef du clan, approuva cette réflexion. Le Clan du Poison était devenu si vulnérable que d'autres clans de haut rang, comme le Clan du Dragon Démoniaque ou d'autres, pourraient même tenter de les renverser.

« Mais si nous refusons, alors nous clamerons à la face du monde que nous sommes devenus faibles ! »

Le deuxième fils de Baek Oh, Baek Munwung, s'était emporté. D'un tempérament agressif, il refusait de voir son clan rabaissé plus longtemps.

« Nous devons être patients. Agir de manière téméraire ne nous aidera en rien dans une telle situation. »

Mais cette réponse ne plut guère à Baek Munwung.

« Notre cousin est toujours cloué au lit, et notre clan est dans un état lamentable ! Qu'attendons-nous de plus ?! »

Il pointa du doigt un petit pavillon de l'autre côté de la cour, où reposait Chun Jongsum. Son énergie interne annihilée et tous ses os brisés, Chun Jongsum avait même eu la moelle épinière détruite ; il ne pouvait plus quitter son lit. Il ne lui restait plus qu'à survivre, et rien de plus.

« Muwung a raison. Ce garçon est déjà un guerrier de niveau supérieur. Mieux vaut l'éliminer maintenant que plus tard. Il sera trop tard si nous le laissons faire, surtout sachant pertinemment la nature de nos relations avec lui. »

Le troisième fils de Baek Oh, Baek Munho, s'exprima avec discernement. Il était terrifiant d'imaginer ce que deviendrait Yeowun s'il était déjà au niveau supérieur. De plus, depuis les souffrances endurées par Baek Oh, et en remontant jusqu'à la mort de Dame Hwa, Yeowun et le Clan du Poison étaient liés par de sombres présages.

« C'est un problème pour tous les clans. Même si ce garçon est devenu puissant, il n'a pas les forces nécessaires pour le soutenir. Est-il une menace ? Non. La véritable menace, c'est le Seigneur. »

Baek Chau prit la parole pour contredire l'idée de Baek Munho. Le seul point positif à tuer Yeowun serait d'éliminer un futur ennemi potentiel. Mais le prix à payer serait d'être banni par le Seigneur et évincé des six clans.

« Vous êtes tous des idiots ! »

« Pour qui te prends-tu pour dire ça ! »

L'assemblée se divisa en deux camps, et les éclats de voix commencèrent à résonner. Baek Oh, qui les écoutait depuis un bon moment, prit finalement sa décision après mûre réflexion.

« Ça suffit ! Je vais refuser cette requête. »

Lui aussi désirait tuer Chun Yeowun plus que quiconque, mais les enjeux étaient trop grands. Il valait mieux laisser quelqu'un d'autre s'en charger. Les dirigeants qui espéraient ce refus approuvèrent, tandis que ses fils ne cachèrent pas leur déception. Une fois tout le monde parti, Baek Oh se rendit dans le petit pavillon où se trouvait Chun Jongsum.

Baek Oh s'assit devant Chun Jongsum, qui clignait des yeux, allongé sur son lit. Il était presque comme mort. Baek Oh avait fait tout ce qui était en son pouvoir pour le soigner, mais même le Docteur Démoniaque en personne n'avait rien pu faire.

« Je suis désolé. Papy ne peut plus rien faire pour t'aider. »

L'incarnation même de la terreur demeurait faible face à son petit-fils. Il était désespéré de devoir se préoccuper de l'avenir de son clan alors que son précieux petit-fils, né de sa précieuse fille, avait été réduit à un tel état. Et Chun Jongsum en avait-il conscience ? Ses yeux s'embuèrent de larmes. C'est à cet instant qu'on l'interrompit.

« Ancien, il y a une invitée. »

« Une invitée à cette heure-ci ? Quel genre d'invitée se présente à une heure pareille ? Renvoyez-la. »

Baek Oh n'était pas d'humeur à recevoir. Mais il dut revoir sa position en entendant le message télépathique suivant :

[C'est Dame Mu, du Clan de la Sagesse. Devons-nous la renvoyer ? Elle est devant votre pavillon.]

Baek Oh fut pris de court. Cette femme ne s'était plus présentée depuis les funérailles de sa fille, Dame Baek.

« Très bien. Je sors. »

Ce n'était pas le genre de personne qu'il pouvait se permettre de renvoyer simplement par manque d'envie. Baek Oh quitta alors la pièce. Au moment où il ouvrait la porte pour sortir, Jongsum roula des yeux pour observer son grand-père.

'?!'

Par l'entrebâillement de la porte, éclairée par la faible lueur des torches, il aperçut la silhouette d'une femme d'âge mûr, le visage recouvert d'un voile rouge. Chun Jongsum, qui parvenait à peine à ouvrir et fermer les yeux, se mit à trembler de tout son être.

'C'est elle ! C'EST ELLE !!!!'

C'était la femme qui avait fourni le poison pour l'assassinat de sa mère. Il voulut hurler, mais sa langue refusait de lui obéir, et il convulsa de rage jusqu'à s'évanouir.

Le lendemain, le conseiller du Clan du Poison se rendit au bureau du Chef de l'Académie Démoniaque. Il lui remit une missive rédigée de la main de Baek Oh, ne contenant qu'une simple phrase.

[Défi accepté.]

Le 12e Ancien, et chef du Clan du Poison, Baek Oh, venait d'accepter le défi.

C'était le matin de la 6e épreuve, un événement inédit depuis soixante-dix ans. Chun Yeowun s'était levé quatre heures avant le duel et s'était rendu chez le forgeron. L'académie était recouverte d'un épais manteau blanc suite aux chutes de neige des jours précédents, mais les environs de la forge étaient détrempés par la neige fondue sous l'effet de la chaleur. La forge, d'ordinaire si bruyante des coups de marteau nocturnes, était désormais silencieuse. Yeowun patienta à l'extérieur une dizaine de minutes avant d'entendre du bruit à l'intérieur, et décida d'entrer.

« Maître Ou ? »

Lorsqu'il pénétra dans les lieux, il y faisait une chaleur étouffante. En s'avançant, Yeowun aperçut Ou Sunong travailler avec la plus grande concentration. Il cousait minutieusement une peau de cuir blanc pour confectionner un fourreau. Ne voulant pas le déranger, Yeowun fit le moins de bruit possible et attendit qu'il termine son ouvrage. Une heure s'écoula ainsi."""

